"""Tests for the paper's RFF feature-count grid (Plist).

MATLAB: Plist = [2, 5:floor(T/10):(T-5), (T-4):2:(T+4),
                 (T+5):floor(T/2):30T, 31T:10T:(maxP-1), maxP]

The expected values below are hand-computed from MATLAB colon semantics
(inclusive of start, last element <= stop) — deliberately NOT generated by
re-implementing the formula, which would test the code against itself.
The grid is dense near P=T because that is the interpolation threshold
where the double-descent spike lives.
"""

from voc.grids import feature_count, plist


def test_plist_t12_structure():
    grid = plist(12)

    assert grid[0] == 2
    assert grid[-1] == 12000
    assert len(grid) == 165
    # Segment boundaries, hand-computed: [2], 5:1:7, 8:2:16, 17:6:359,
    # 372:120:11892, 12000.
    assert grid[:10] == [2, 5, 6, 7, 8, 10, 12, 14, 16, 17]
    assert 359 in grid and 365 not in grid
    assert grid[-3:] == [11772, 11892, 12000]


def test_plist_t60_structure():
    grid = plist(60)

    assert len(grid) == 91
    # [2], 5:6:53, 56:2:64, 65:30:1775, 1860:600:11460, 12000.
    assert grid[:11] == [2, 5, 11, 17, 23, 29, 35, 41, 47, 53, 56]
    assert grid[10:15] == [56, 58, 60, 62, 64]
    assert 1775 in grid and 1805 not in grid
    assert grid[-3:] == [10860, 11460, 12000]


def test_plist_t120_structure():
    grid = plist(120)

    assert len(grid) == 82
    # [2], 5:12:113, 116:2:124, 125:60:3545, 3720:1200:10920, 12000.
    assert grid[:12] == [2, 5, 17, 29, 41, 53, 65, 77, 89, 101, 113, 116]
    assert grid[11:16] == [116, 118, 120, 122, 124]
    assert 3545 in grid and 3605 not in grid
    assert grid[-3:] == [9720, 10920, 12000]


def test_plist_is_sorted_and_spans_interpolation_threshold():
    for window in (12, 60, 120):
        grid = plist(window)
        assert grid == sorted(grid)
        # The dense +-4 band around P=T must be present (c = P/T ~ 1).
        for offset in (-4, -2, 0, 2, 4):
            assert window + offset in grid


def test_feature_count_is_twice_half_p():
    # MATLAB draws floor(P/2) weight rows and stacks [cos; sin], so odd
    # grid values lose one feature: P=5 -> 4 actual features.
    assert feature_count(2) == 2
    assert feature_count(5) == 4
    assert feature_count(12) == 12
    assert feature_count(17) == 16
    assert feature_count(12000) == 12000
